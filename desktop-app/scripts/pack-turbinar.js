'use strict';

// Puts the "Turbine seu fliperama" bundle (built by _TEMA_FLIPERAMA/tools/product.py)
// inside the app, encrypted (AES-256-GCM): resources/turbinar/turbinar.bin + VERSION.
// The key stays on the seller's PC (%USERPROFILE%\.arcade-do-zero\payload.key) and goes
// into the build as src/turbinar-key.js, which git ignores.
//   node scripts/pack-turbinar.js [path/to/turbinar.tar.gz]

const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

const APP = path.join(__dirname, '..');
const SRC = process.argv[2] || path.join(APP, '..', '..', '_TEMA_FLIPERAMA', 'dist', 'turbinar.tar.gz');
const VERSION_FILE = path.join(path.dirname(SRC), 'turbinar', 'VERSION');
const OUT = path.join(APP, 'resources', 'turbinar');
const KEY_FILE = path.join(os.homedir(), '.arcade-do-zero', 'payload.key');

if (!fs.existsSync(KEY_FILE)) {
  fs.mkdirSync(path.dirname(KEY_FILE), { recursive: true });
  fs.writeFileSync(KEY_FILE, crypto.randomBytes(32).toString('base64'), { mode: 0o600 });
}
const key = Buffer.from(fs.readFileSync(KEY_FILE, 'utf8').trim(), 'base64');
fs.writeFileSync(path.join(APP, 'src', 'turbinar-key.js'),
  `'use strict';\n// Generated by scripts/pack-turbinar.js. Not in git.\nmodule.exports = Buffer.from('${key.toString('base64')}', 'base64');\n`);

const plain = fs.readFileSync(SRC);
const iv = crypto.randomBytes(12);
const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
const body = Buffer.concat([cipher.update(plain), cipher.final()]);
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'turbinar.bin'), Buffer.concat([Buffer.from('ADZT1'), iv, cipher.getAuthTag(), body]));
const version = fs.readFileSync(VERSION_FILE, 'utf8').trim();
fs.writeFileSync(path.join(OUT, 'VERSION'), version + '\n');
console.log(`turbinar ${version}: ${Math.round(plain.length / 1024)} KB -> resources/turbinar/turbinar.bin`);
